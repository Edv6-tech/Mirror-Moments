'use client';

import React, { useState, useCallback } from 'react';
import Link from 'next/link';
import {
  ArrowLeft,
  Download,
  RotateCcw,
  Sparkles,
  Eye,
} from 'lucide-react';
import clsx from 'clsx';
import { Button, ImageInput, DemoPreviewNotice } from '@/components/ui';
import FX6CurtainReveal from '@/components/effects/FX6CurtainReveal';
import FX5WeavingLoader from '@/components/effects/FX5WeavingLoader';
import FX7TiltCard from '@/components/effects/FX7TiltCard';

type AsyncState = 'idle' | 'loading' | 'success' | 'error';

// ── Lens colour presets ────────────────────────────────────────────────────────
// Each preset maps to a locally-generated PNG in public/lenses/<id>.png.
// The route reads the file from disk and uploads it to the feature-specific
// endpoint /s2s/v2.0/file/eye-color-vto to get a ref_file_id.
// Generated by scripts/generate-lenses.mjs — 400×400 RGBA iris PNGs.
const LENS_PRESETS = [
  { id: 'natural_hazel', name: 'Natural Hazel', color: '#8B6914' },
  { id: 'honey_brown',   name: 'Honey Brown',   color: '#C68B37' },
  { id: 'ocean_blue',    name: 'Ocean Blue',     color: '#1565C0' },
  { id: 'forest_green',  name: 'Forest Green',   color: '#2E7D32' },
  { id: 'violet',        name: 'Violet',         color: '#6A1B9A' },
  { id: 'storm_grey',    name: 'Storm Grey',     color: '#546E7A' },
  { id: 'icy_blue',      name: 'Icy Blue',       color: '#4FC3F7' },
  { id: 'amethyst',      name: 'Amethyst',       color: '#9C27B0' },
] as const;

const SAMPLE_EYE_PORTRAIT = '/samples/portrait-eyecolor.jpg';

type LensId = typeof LENS_PRESETS[number]['id'];

export default function EyeColorPage() {
  const [selfieFile,    setSelfieFile]    = useState<File | null>(null);
  const [selfieUrl,     setSelfieUrl]     = useState<string | null>(null);
  const [selfiePreview, setSelfiePreview] = useState<string | null>(null);
  const [selectedLens,  setSelectedLens]  = useState<LensId>('ocean_blue');
  const [state,         setState]         = useState<AsyncState>('idle');
  const [resultUrl,     setResultUrl]     = useState<string | null>(null);
  const [isMockResult, setIsMockResult] = useState(false);
  const [errorMsg,      setErrorMsg]      = useState<string | null>(null);

  const handleSelfieFile = useCallback((file: File) => {
    setSelfieFile(file);
    setSelfieUrl(null);
    setSelfiePreview(URL.createObjectURL(file));
    setResultUrl(null);
    setState('idle');
  }, []);

  const handleSelfieUrl = useCallback((url: string) => {
    setSelfieUrl(url);
    setSelfieFile(null);
    setSelfiePreview(url);
    setResultUrl(null);
    setState('idle');
  }, []);

  const reset = () => {
    setSelfieFile(null);
    setSelfieUrl(null);
    setSelfiePreview(null);
    setResultUrl(null);
    setErrorMsg(null);
    setState('idle');
  };

  const handleApply = async () => {
    setState('loading');
    setErrorMsg(null);

    try {
      const form = new FormData();
      if (selfieFile) {
        form.append('selfiePhoto', selfieFile);
      } else if (selfieUrl) {
        form.append('selfieUrl', selfieUrl);
      }
      // Send the preset id — route reads public/lenses/<id>.png and uploads it
      form.append('lensId', selectedLens);

      const res  = await fetch('/api/eye-color-vto', { method: 'POST', body: form });
      const data = await res.json();

      if (!res.ok || !data.ok) throw new Error(data.message ?? 'Eye Color VTO failed.');
      if (typeof data.resultUrl !== 'string' || !data.resultUrl) throw new Error('Eye-colour try-on finished without returning a preview. Please try again.');
      setResultUrl(data.resultUrl as string);
      setIsMockResult(Boolean(data.mock));
      setState('success');
    } catch (err: unknown) {
      const msg = err instanceof Error ? err.message : 'Something went wrong.';
      setErrorMsg(msg);
      setState('error');
    }
  };

  const activeLens = LENS_PRESETS.find((l) => l.id === selectedLens)!;

  return (
    <div
      className="min-h-screen py-8 mirror-studio"
      style={{ background: 'var(--grad-silk-light)' }}
    >
      <div className="max-w-4xl mx-auto px-4 sm:px-6 lg:px-8 space-y-8">
        <Link href="/app" className="inline-flex items-center gap-1.5 text-xs font-semibold text-white/50 hover:text-white transition-colors">
          <ArrowLeft size={14} /> Back to Dashboard
        </Link>

        <header className="flex items-center gap-3">
          <div className="w-12 h-12 rounded-2xl bg-dashboard-gradient text-white flex items-center justify-center shadow-xl">
            <Eye size={22} />
          </div>
          <div>
            <h1 className="font-display text-3xl sm:text-4xl font-semibold text-white">AI Eye Colour Lens</h1>
            <p className="text-sm text-white/50 mt-0.5">Try on coloured contact lenses with hyper-realistic iris rendering</p>
          </div>
        </header>

        <div className="grid grid-cols-1 lg:grid-cols-2 gap-6">
          {/* ── Controls ── */}
          <div className="space-y-5">
            <section className="p-5 rounded-3xl border border-white/10 space-y-3" style={{ background: 'rgba(255,255,255,0.05)', backdropFilter: 'blur(16px)' }}>
              <p className="text-xs font-bold uppercase tracking-wider text-white/50">Step 1 — Your Photo</p>
              <p className="text-xs text-white/40">Face forward, long side ≤ 1920 px, short side ≥ 320 px, max 10 MB. Upload a file or paste a direct HTTPS image link — skipping uses a sample.</p>
              <ImageInput
                onFileSelect={handleSelfieFile}
                onUrlSelect={handleSelfieUrl}
                onClear={() => { setSelfieFile(null); setSelfieUrl(null); setSelfiePreview(null); }}
                label="Upload selfie or paste an image link"
                hint="JPG / PNG · face forward · max 10 MB"
              />
              <button type="button" onClick={() => handleSelfieUrl(SAMPLE_EYE_PORTRAIT)} aria-pressed={selfieUrl === SAMPLE_EYE_PORTRAIT}
                className="flex w-full items-center gap-3 rounded-2xl border border-[var(--line)] bg-white/75 p-2 text-left transition hover:border-[var(--blue-500)] focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-[var(--blue-600)]">
                {/* eslint-disable-next-line @next/next/no-img-element */}
                <img src={SAMPLE_EYE_PORTRAIT} alt="" className="h-14 w-14 rounded-xl object-cover" />
                <span><span className="block text-xs font-semibold text-[var(--ink-900)]">Use sample portrait</span><span className="mt-0.5 block text-[10px] text-[var(--ink-500)]">A blue-eyed model photo, ready to preview</span></span>
              </button>
            </section>

            <section className="p-5 rounded-3xl border border-white/10 space-y-4" style={{ background: 'rgba(255,255,255,0.05)', backdropFilter: 'blur(16px)' }}>
              <p className="text-xs font-bold uppercase tracking-wider text-white/50">Step 2 — Choose Lens Colour</p>
              <div className="grid grid-cols-4 gap-2">
                {LENS_PRESETS.map((lens) => (
                  <FX7TiltCard key={lens.id} maxDeg={8} className="cursor-pointer">
                    <button
                      onClick={() => setSelectedLens(lens.id)}
                      aria-label={lens.name}
                      aria-pressed={selectedLens === lens.id}
                      title={lens.name}
                      className={clsx(
                        'w-full flex flex-col items-center gap-1.5 p-2 rounded-2xl border-2 transition-all focus-visible:ring-2 focus-visible:ring-[var(--sky-400)]',
                        selectedLens === lens.id
                          ? 'border-[var(--sky-400)] shadow-[0_0_14px_rgba(234,56,77,0.28)] bg-white/10'
                          : 'border-white/10 hover:border-white/30 bg-white/5'
                      )}
                    >
                      <div
                        className="relative w-10 h-10 rounded-full shadow-md ring-2 ring-black/20"
                        style={{ backgroundColor: lens.color }}
                      >
                        <div className="absolute inset-[30%] rounded-full bg-black/80" />
                        <div className="absolute inset-[42%] rounded-full bg-white/30" />
                      </div>
                      <span className="text-[9px] font-semibold text-white/70 text-center leading-tight">{lens.name}</span>
                    </button>
                  </FX7TiltCard>
                ))}
              </div>
              <div className="px-3 py-2 rounded-xl border border-white/10 flex items-center gap-2" style={{ background: 'rgba(255,255,255,0.05)' }}>
                <div className="relative w-5 h-5 rounded-full ring-1 ring-black/20 shrink-0" style={{ backgroundColor: activeLens.color }}>
                  <div className="absolute inset-[28%] rounded-full bg-black/80" />
                </div>
                <span className="text-xs font-semibold text-white">{activeLens.name}</span>
              </div>
            </section>

            <Button variant="primary" size="lg" leftIcon={<Sparkles size={18} />} onClick={handleApply} disabled={state === 'loading'} className="w-full">
              {state === 'loading' ? 'Applying lens…' : 'Apply Lens'}
            </Button>

            {state === 'error' && errorMsg && (
              <div role="alert" className="p-4 rounded-2xl border border-[var(--danger)]/30 text-sm text-[var(--danger)]" style={{ background: 'rgba(229,72,77,0.1)' }}>{errorMsg}</div>
            )}
          </div>

          {/* ── Result ── */}
          <div className="space-y-4">
            {state === 'loading' && (
              <div className="rounded-3xl overflow-hidden aspect-[3/4] bg-[var(--navy-950)] flex items-center justify-center">
                <FX5WeavingLoader personUrl={selfiePreview ?? undefined} />
              </div>
            )}
            {state === 'success' && resultUrl && (
              <div className="space-y-3">
              {isMockResult && <DemoPreviewNotice />}
              <FX6CurtainReveal>
                <div className="rounded-3xl overflow-hidden aspect-[3/4]">
                  {/* eslint-disable-next-line @next/next/no-img-element */}
                  <img src={resultUrl} alt="Eye color lens try-on result" className="w-full h-full object-cover" />
                </div>
              </FX6CurtainReveal>
              </div>
            )}
            {(state === 'idle' || state === 'error') && (
              <div className="relative rounded-3xl overflow-hidden aspect-[3/4] bg-[var(--ice-100)] shadow-[var(--shadow-soft)]">
                {/* eslint-disable-next-line @next/next/no-img-element */}
                <img src={SAMPLE_EYE_PORTRAIT} alt="Portrait of a woman with clear blue eyes, shown as eye-colour inspiration" className="w-full h-full object-cover object-center" />
                <div className="absolute inset-x-4 bottom-4 rounded-2xl border border-white/80 bg-white/90 p-4 shadow-lg backdrop-blur-sm">
                  <p className="text-sm font-semibold text-[var(--ink-900)]">Preview a new eye colour</p>
                  <p className="mt-1 text-xs leading-relaxed text-[var(--ink-500)]">Upload your own photo and choose a lens shade to see your personalized result.</p>
                </div>
              </div>
            )}
            {state === 'success' && resultUrl && (
              <div className="flex gap-3">
                <a href={resultUrl} download="mirror_moment_eye_color.jpg" className="flex-1">
                  <Button variant="primary" size="md" leftIcon={<Download size={16} />} className="w-full">Download</Button>
                </a>
                <Button variant="secondary" size="md" leftIcon={<RotateCcw size={16} />} onClick={reset}>Reset</Button>
              </div>
            )}
            <div className="p-3 rounded-2xl border border-white/10 text-xs text-white/40 leading-relaxed" style={{ background: 'rgba(255,255,255,0.04)' }}>
              <strong className="text-white/70">Best results:</strong> Bright, even lighting. Eyes open and looking directly at camera. No sunglasses or heavy eye makeup.
            </div>
          </div>
        </div>
      </div>
    </div>
  );
}
